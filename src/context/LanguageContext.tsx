// ─── Context ───────────────────────────────────────────────────────────────

interface LanguageContextType {
  language: string;
  setLanguage: (code: string) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  translateCategory: (categoryTitle: string) => string;
  currentLang: Language;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'EN',
  setLanguage: () => {},
  t: (key) => key,
  translateCategory: (cat) => cat,
  currentLang: SUPPORTED_LANGUAGES[0],
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLangState] = useState<string>(() =>
    localStorage.getItem('jayveermart_lang') || localStorage.getItem('nexusmart_lang') || 'EN'
  );

  useEffect(() => {
    document.documentElement.lang = language.toLowerCase();
  }, [language]);

  const setLanguage = useCallback((code: string) => {
    setLangState(code);
    localStorage.setItem('jayveermart_lang', code);
    document.documentElement.lang = code.toLowerCase();
  }, []);

  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>): string => {
      const langMap = translations[language] || translations['EN'];
      let val = langMap[key] || translations['EN'][key] || key;
      if (params) {
        Object.entries(params).forEach(([k, v]) => {
          val = val.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        });
      }
      return val;
    },
    [language]
  );

  const translateCategory = useCallback(
    (catTitle: string): string => {
      if (!catTitle) return '';
      const normalized = catTitle.trim();
      switch (normalized) {
        case 'Electronics': return t('electronics');
        case 'Ladies Wears': return t('ladiesWears');
        case 'Mens Wear': return t('mensWear');
        case 'Kids Wear': return t('kidsWear');
        case 'Furnitures': return t('furnitures');
        case 'Home Appliances': return t('homeAppliances');
        case 'Sports': return t('sports');
        case 'Fashion': return t('fashion');
        case 'Home & Kitchen': return t('homeKitchen');
        default: return normalized;
      }
    },
    [t]
  );

  const currentLang = SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, translateCategory, currentLang }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
